def main() -> int:
    history = load_json(HISTORY_FILE, [])
    sync_info = load_json(SYNC_FILE, {})

    if not isinstance(history, list):
        history = []
    if not isinstance(sync_info, dict):
        sync_info = {}

    response = requests.get(
        CATALOG_URL,
        timeout=HTTP_TIMEOUT,
        headers={"User-Agent": USER_AGENT},
    )
    response.raise_for_status()
    catalog = response.json()
    index = catalog_repo_index(catalog)

    # PSVitaAlive itself is the catalog/store project, so it may not appear as a
    # normal catalog entry. Pull its latest release explicitly so a new Store
    # release is visible immediately whenever the dashboard rebuilds.
    self_release = fetch_psvitaalive_latest_release()
    if self_release:
        history.append(self_release)

    history, exact_removed = dedupe_exact_history(history)

    matched = 0
    with_icon = 0

    for release in history:
        if not isinstance(release, dict):
            continue

        key = repo_key(
            str(release.get("platform") or "github"),
            str(release.get("repo") or ""),
        )
        apps = index.get(key, [])

        if apps or key == PSVITAALIVE_REPO_KEY:
            matched += 1

        enrich_release(release, apps)

        if release.get("homebrew_icon"):
            with_icon += 1

    history, older_hidden = collapse_latest_per_app(history)

    # From this point releases.json is intentionally a current-state data set,
    # not an archive: exactly one newest release per app.
    save_json(HISTORY_FILE, history)

    up_to_date = sum(
        1 for item in history
        if item.get("catalog_update_status") == "uptodate"
    )
    pending = len(history) - up_to_date

    sync_info["catalog_metadata_matches"] = matched
    sync_info["catalog_icons"] = with_icon
    sync_info["metadata_enriched_at"] = datetime.now(timezone.utc).isoformat()
    sync_info["exact_duplicates_removed"] = exact_removed
    sync_info["older_app_releases_removed"] = older_hidden
    sync_info["catalog_up_to_date"] = up_to_date
    sync_info["catalog_pending"] = pending
    sync_info["dashboard_apps"] = len(history)
    sync_info["psvitaalive_self_release"] = str(self_release.get("tag") or "") if self_release else ""

    save_json(SYNC_FILE, sync_info)
    generate_dashboard(history, sync_info)

    print(
        f"🎨 Dashboard: {len(history)} apps únicas; "
        f"{up_to_date} al día; {pending} pendientes; "
        f"{exact_removed} duplicados exactos eliminados; "
        f"{older_hidden} releases antiguos/repetidos eliminados; "
        f"PSVitaAlive={sync_info.get('psvitaalive_self_release') or 'N/A'}."
    )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
