def enrich_release(release: dict[str, Any], apps: list[dict[str, Any]]) -> None:
    current_repo_key = repo_key(
        str(release.get("platform") or "github"),
        str(release.get("repo") or ""),
    )

    if current_repo_key == PSVITAALIVE_REPO_KEY:
        apps = [self_app_metadata(release)]

    if not apps:
        clear_catalog_metadata(release)
        status, detail = calculate_catalog_status(release, None)
        release["catalog_update_status"] = status
        release["catalog_update_detail"] = detail
        release["catalog_version"] = ""
        return

    primary = choose_primary_app(apps, release) or apps[0]
    ordered = [primary] + [app for app in apps if app is not primary]

    release["homebrew_name"] = primary.get("name") or release.get("name") or release.get("repo")
    release["homebrew_icon"] = primary.get("icon") or ""
    release["homebrew_category"] = primary.get("category") or ""
    release["homebrew_description"] = primary.get("description") or ""
    release["homebrew_long_description"] = primary.get("long_description") or ""
    release["homebrew_id"] = primary.get("id") or ""
    release["homebrew_authors"] = primary.get("author_ids") or []
    release["homebrew_version"] = primary.get("version") or ""
    release["catalog_apps"] = ordered[:12]

    status, detail = calculate_catalog_status(release, primary)
    release["catalog_update_status"] = status
    release["catalog_update_detail"] = detail
    release["catalog_version"] = primary.get("version") or ""


def github_headers() -> dict[str, str]:
    headers = {
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "User-Agent": USER_AGENT,
    }
    if GITHUB_TOKEN:
        headers["Authorization"] = f"Bearer {GITHUB_TOKEN}"
    return headers


def fetch_psvitaalive_latest_release() -> dict[str, Any] | None:
    url = f"https://api.github.com/repos/{PSVITAALIVE_REPO}/releases/latest"

    try:
        response = requests.get(url, headers=github_headers(), timeout=HTTP_TIMEOUT)
        response.raise_for_status()
        item = response.json()
    except (requests.RequestException, ValueError) as exc:
        print(f"⚠️ No se pudo consultar el release de PSVitaAlive: {exc}")
        return None

    assets = []
    for asset in item.get("assets") or []:
        if not isinstance(asset, dict) or not asset.get("browser_download_url"):
            continue
        assets.append(
            {
                "name": asset.get("name") or "archivo",
                "size": asset.get("size", 0) or 0,
                "download_url": asset.get("browser_download_url") or "",
                "content_type": asset.get("content_type") or "",
            }
        )

    return {
        "platform": "github",
        "repo": PSVITAALIVE_REPO,
        "release_id": str(item.get("id") or item.get("tag_name") or ""),
        "tag": item.get("tag_name") or "",
        "name": item.get("name") or item.get("tag_name") or "PSVitaAlive Store",
        "url": item.get("html_url") or f"https://github.com/{PSVITAALIVE_REPO}/releases",
        "published": item.get("published_at") or item.get("created_at") or "",
        "prerelease": bool(item.get("prerelease")),
        "draft": False,
        "body": item.get("body") or "",
        "assets": assets,
        "author": (item.get("author") or {}).get("login") or "VegettoSan",
    }


def exact_release_key(item: dict[str, Any]) -> str:
    platform = str(item.get("platform") or "github").lower()
    repo = str(item.get("repo") or "").strip().lower()
    tag = str(item.get("tag") or "").strip().lower()

    if tag:
        return f"{platform}:{repo}:{tag}"

    release_id = str(item.get("release_id") or "").strip().lower()
    if release_id:
        return f"{platform}:{repo}:{release_id}"

    url = str(item.get("url") or "").strip().lower()
    if url:
        return f"{platform}:{repo}:{url}"

    return f"{platform}:{repo}:{item.get('published') or ''}"


def merge_release_records(
    preferred: dict[str, Any],
    other: dict[str, Any],
) -> dict[str, Any]:
    result = dict(preferred)

    for key, value in other.items():
        current = result.get(key)

        if current in (None, "", [], {}):
            result[key] = value
            continue

        if key == "assets" and isinstance(current, list) and isinstance(value, list):
            known = {
                str(asset.get("download_url") or asset.get("name") or "")
                for asset in current
                if isinstance(asset, dict)
            }
            merged = list(current)
            for asset in value:
                if not isinstance(asset, dict):
                    continue
                identity = str(asset.get("download_url") or asset.get("name") or "")
                if identity and identity not in known:
                    known.add(identity)
                    merged.append(asset)
            result[key] = merged

    return result


def dedupe_exact_history(
    history: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], int]:
    ordered = sorted(
        (item for item in history if isinstance(item, dict)),
        key=lambda item: parse_published(item.get("published")),
        reverse=True,
    )

    unique: dict[str, dict[str, Any]] = {}
    removed = 0

    for item in ordered:
        key = exact_release_key(item)
        if key not in unique:
            unique[key] = item
        else:
            unique[key] = merge_release_records(unique[key], item)
            removed += 1

    return list(unique.values()), removed


def display_identity(item: dict[str, Any]) -> str:
    homebrew_id = normalized_text(item.get("homebrew_id"))
    if homebrew_id:
        return f"app:{homebrew_id}"

    homebrew_name = normalized_text(item.get("homebrew_name"))
    if homebrew_name:
        return f"name:{homebrew_name}"

    return repo_key(
        str(item.get("platform") or "github"),
        str(item.get("repo") or ""),
    )


def release_rank(item: dict[str, Any]) -> tuple[datetime, tuple[int, ...]]:
    published = parse_published(item.get("published"))
    numbers, _ = version_signature(item.get("tag") or item.get("name"))
    return published, numbers or tuple()


def collapse_latest_per_app(
    history: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], int]:
    """Return exactly one release per app, always the newest known release."""
    chosen: dict[str, dict[str, Any]] = {}
    hidden = 0

    for item in history:
        if not isinstance(item, dict):
            continue

        identity = display_identity(item)
        current = chosen.get(identity)

        if current is None:
            chosen[identity] = item
            continue

        hidden += 1
        if release_rank(item) > release_rank(current):
            chosen[identity] = item

    result = sorted(
        chosen.values(),
        key=lambda item: release_rank(item),
        reverse=True,
    )

    # Second visual safety pass: duplicate catalog records can occasionally use
    # different IDs but the same canonical display name. Keep only the newest.
    final: list[dict[str, Any]] = []
    seen_names: set[str] = set()

    for item in result:
        name = normalized_text(item.get("homebrew_name"))
        if name and name in seen_names:
            hidden += 1
            continue
        if name:
            seen_names.add(name)
        final.append(item)

    return final[:MAX_PROJECTS], hidden


def format_size(size: int | float | None) -> str:
    if not size:
        return ""

    value = float(size)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if value < 1024 or unit == "TB":
            return f"{value:.1f} {unit}"
        value /= 1024

    return ""


def choose_primary_asset(assets: list[dict[str, Any]]) -> dict[str, Any] | None:
    if not assets:
        return None

    for extension in (".vpk", ".skprx", ".suprx", ".self", ".zip"):
        for asset in assets:
            if str(asset.get("name") or "").lower().endswith(extension):
                return asset

    return assets[0]


def render_release_body(raw: Any) -> str:
    text = str(raw or "").strip()

    if not text:
        return "<p>Sin descripción.</p>"

    try:
        rendered = MARKDOWN(text)
    except Exception:
        rendered = f"<pre>{esc(text)}</pre>"

    cleaned = bleach.clean(
        rendered,
        tags=ALLOWED_TAGS,
        attributes=ALLOWED_ATTRIBUTES,
        protocols=ALLOWED_PROTOCOLS,
        strip=True,
    )

    cleaned = re.sub(
        r"<a(?![^>]*\btarget=)([^>]*)>",
        r'<a target="_blank" rel="noopener noreferrer"\1>',
        cleaned,
        flags=re.IGNORECASE,
    )

    return cleaned


